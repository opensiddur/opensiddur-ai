def locate(text,incipit,start=0):
    """Locate a read incipit without changing the edition's pointing or punctuation."""
    def letters(value):
        return ''.join(c.lower() for c in value if c.isalpha())
    positions=[i for i,c in enumerate(text) if c.isalpha() and i>=start]
    normalized=''.join(text[i].lower() for i in positions)
    i=normalized.find(letters(incipit))
    if i<0:raise ValueError(('Incipit missing',incipit,text[start:start+120]))
    position=positions[i]
    while position>start and text[position-1] in "[“":
        position-=1
    return position


def split(text,boundaries,lang):
    side=int(lang=='en');starts=[];cursor=0
    for urn,he,en in boundaries:
        position=locate(text,(he,en)[side],cursor)
        starts.append((urn,position));cursor=position+1
    starts[0]=(starts[0][0],0)
    starts.append(('',len(text)))
    return [(urn,text[a:b].strip()) for (urn,a),(_,b) in zip(starts,starts[1:])]

