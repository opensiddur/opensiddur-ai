def megillah_quotes(text,lang):
    side=int(lang=='en');positions=[];cursor=0
    for ref,hs,he,es,ee in MEGILLAH_QUOTES:
        start=locate(text,(hs,es)[side],cursor)
        end_start=locate(text,(he,ee)[side],start)
        # Include the entire closing phrase, retaining its original pointing.
        letters=sum(c.isalpha() for c in (he,ee)[side]);end=end_start
        while letters:
            letters-=int(text[end].isalpha());end+=1
        import unicodedata
        while end<len(text) and unicodedata.category(text[end]).startswith('M'):end+=1
        positions.append((start,end,ref));cursor=end
    for start,end,ref in reversed(positions):
        text=text[:start]+'{q:'+ref+'}'+text[start:end]+'{/q}'+text[end:]
    return text
