"""The English of the Akedah and the setting for the Shema, printed pages 20 to 26.

**The Akedah is one paragraph in Hebrew and four in English.** Both sides carry one
`prayer:akedah`, so the two columns join at the division and each parts its own prose.

**`לְפִיכָךְ` and `אַתָּה הוּא` are parted in Hebrew and not in English.** Printed 25 sets a
`Reader` label inside each, which makes the second half its own text with its own URN;
printed 26 runs straight on. The English is parted at the same two points so that the two
sides join URN for URN -- a passage that must start level with its translation needs a URN
of its own, and here the Hebrew page is what creates it.

The Shema verse and Barukh Shem are realised by the children's unit and transcluded.

Generated by `specs/birnbaum_scan/generate_english_modules.py` from the English readings,
and checked page by page with `reverse`.
"""
import functools

