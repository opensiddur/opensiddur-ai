"""The English of Rabbi Ishmael's rules and Kaddish d'Rabbanan, printed 42 to 48.

**This side carries a heading the Hebrew side does not** -- `TALMUDIC EXPOSITION OF THE
SCRIPTURES`, centred in small capitals over printed 42, where printed 41 goes straight from
the tail of Zevaḥim to its citation. It is in the unit body, not here.

The rules are numbered `1.` here and `א)` there; the closing rubric names **page 300** here
and page 299 there, each side pointing at its own half of the target opening.

Generated by `specs/birnbaum_scan/generate_english_modules.py` from the English readings,
and checked page by page with `reverse`.
"""
import functools

from .common import PRAYER, POEM
from . import common

pb = functools.partial(common.pb, sigil=common.SIGIL_BIRCHOT)

U = PRAYER
P = POEM

PRAYERS = []


def prayer(name, title, slug, first, last, body, *, base=None):
    PRAYERS.append(dict(name=name, title=title, urn=(base or U) + slug,
                        first=first, last=last, body=body))


def d(urn, *paras, indent=8):
    pad = " " * indent
    inner = "\n".join(f"{pad}  <tei:p>{p}</tei:p>" for p in paras)
    return f'{pad}<tei:div corresp="{urn}">\n{inner}\n{pad}</tei:div>'


def verses(urn, ls, *, indent=8):
    pad = " " * indent
    inner = "\n".join(f"{pad}    <tei:l>{line}</tei:l>" for line in ls)
    return ('%s<tei:div corresp="%s">\n%s  <tei:lg>\n%s\n%s  </tei:lg>\n%s</tei:div>'
            % (pad, urn, pad, inner, pad, pad))


